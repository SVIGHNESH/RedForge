// Command rtm writes docs/RTM.md, the requirements traceability matrix.
//
// It reads the task issues and pull requests from GitHub through the gh CLI,
// so the matrix always reflects the live "Blocked by" links, assignees and PR
// state rather than a hand-maintained copy. Run it from the repository root:
//
//	go run ./scripts/tasks/rtm > docs/RTM.md
//
// REPO overrides the repository (default SVIGHNESH/RedForge).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type issue struct {
	Number    int    `json:"number"`
	Title     string `json:"title"`
	State     string `json:"state"`
	Body      string `json:"body"`
	Assignees []struct {
		Login string `json:"login"`
	} `json:"assignees"`
	Labels []struct {
		Name string `json:"name"`
	} `json:"labels"`
}

type pull struct {
	Number      int    `json:"number"`
	State       string `json:"state"`
	Body        string `json:"body"`
	BaseRefName string `json:"baseRefName"`
	HeadRefName string `json:"headRefName"`
}

// people maps GitHub logins to the names the task files use.
var people = map[string]string{
	"SVIGHNESH":       "Vighnesh",
	"rajat2618":       "Rajat",
	"R1T1KKUMAR":      "Ritik",
	"Viveksharma8542": "Vivek",
}

// objectives is MASTER-PLAN Section 1.1: proposal item to synopsis objective.
var objectives = []struct{ items, objective, verified string }{
	{"M1, M2", "Obj 1: RESP2 codec, single-threaded non-blocking loop, unmodified redis-cli", "redis-cli session, 100-client test"},
	{"M3, M4, M5, M6", "Obj 2: strings, expiry, lists, hashes, sets with absolute timestamps", "invariant tests, expiry-across-restart tests"},
	{"M7, M8", "Obj 3: hybrid persistence with checksummed sequenced log and atomic snapshots", "four crash-recovery tests"},
	{"M9", "Obj 4: one-command correctness suite with SIGKILL, expiry and 100-client cases", "CI green from clean checkout"},
	{"M10", "Obj 5: five-scenario evaluation against official Redis with attribution", "comparison tables, charts, attribution text"},
	{"S1, S2, S3, S4, S5", "Obj 6: extensions in priority order", "per-extension tests"},
	{"M11", "Deliverable 6: README, diagrams, Docker Compose, final report", "reviewer checklist"},
}

var (
	reBlocked  = regexp.MustCompile(`(?m)^Blocked by:(.*)$`)
	reRef      = regexp.MustCompile(`#(\d+)`)
	reReviewer = regexp.MustCompile(`\*\*Reviewer:\*\*\s*([^|\n]+)`)
	reTaskFile = regexp.MustCompile(`docs/tasks/(t[0-9a-z-]+\.md)`)
	reCloses   = regexp.MustCompile(`(?i)\b(?:closes|fixes|resolves|refs)\s+#(\d+)`)
	reTaskID   = regexp.MustCompile(`^(T\d+\.\d+)\s+(.*)$`)
	reDepends  = regexp.MustCompile(`\*\*Depends on:\*\*\s*([^\n]+)`)
	reIDRange  = regexp.MustCompile(`T(\d+)\.(\d+)(?:\s+to\s+T(\d+)\.(\d+))?`)
)

func gh(v any, args ...string) {
	cmd := exec.Command("gh", args...)
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintln(os.Stderr, "rtm: gh", strings.Join(args, " "), ":", err)
		os.Exit(1)
	}
	if err := json.Unmarshal(out.Bytes(), v); err != nil {
		fmt.Fprintln(os.Stderr, "rtm: decode:", err)
		os.Exit(1)
	}
}

func main() {
	repo := os.Getenv("REPO")
	if repo == "" {
		repo = "SVIGHNESH/RedForge"
	}
	var issues []issue
	gh(&issues, "issue", "list", "-R", repo, "--state", "all", "--limit", "500",
		"--json", "number,title,state,body,assignees,labels")
	var pulls []pull
	gh(&pulls, "pr", "list", "-R", repo, "--state", "all", "--limit", "500",
		"--json", "number,state,body,baseRefName,headRefName")

	byNum := map[int]*issue{}
	var tasks []*issue
	for i := range issues {
		is := &issues[i]
		byNum[is.Number] = is
		if hasLabel(is, "task") {
			tasks = append(tasks, is)
		}
	}
	sort.Slice(tasks, func(a, b int) bool { return tasks[a].Number < tasks[b].Number })

	idToIssue := map[string]int{}
	for _, t := range tasks {
		if m := reTaskID.FindStringSubmatch(t.Title); m != nil {
			idToIssue[m[1]] = t.Number
		}
	}

	blockedBy := map[int][]int{}
	unblocks := map[int][]int{}
	for _, t := range tasks {
		for _, n := range blockers(t) {
			blockedBy[t.Number] = append(blockedBy[t.Number], n)
			unblocks[n] = append(unblocks[n], t.Number)
		}
	}

	prsFor := map[int][]pull{}
	headPR := map[string]int{}
	for _, p := range pulls {
		headPR[p.HeadRefName] = p.Number
		for _, m := range reCloses.FindAllStringSubmatch(p.Body, -1) {
			n, _ := strconv.Atoi(m[1])
			prsFor[n] = append(prsFor[n], p)
		}
	}

	w := &strings.Builder{}
	p := func(format string, a ...any) { fmt.Fprintf(w, format, a...) }

	p("# Requirements Traceability Matrix\n\n")
	p("Generated by `make rtm` (`scripts/tasks/rtm`) from the GitHub issues and pull requests of `%s`.\n", repo)
	p("Do not edit by hand: rerun the generator after issues, assignees or PRs change.\n")
	p("Dependencies come from the `Blocked by:` line of each issue, which `scripts/tasks/sync-issues.sh` writes from the task files.\n\n")

	p("## How to read it\n\n")
	p("- **Requirement** is the proposal item (M1 to M11 Must, S1 to S5 Stretch) and the synopsis objective it serves (MASTER-PLAN Section 1.1).\n")
	p("- **Blocked by** lists every issue that must merge first, with its owner, so it shows whose work is holding a task.\n")
	p("A ticked blocker (`#7 ✓`) is closed.\n")
	p("- **Unblocks** is the reverse edge: the issues waiting on this one.\n")
	p("- **Status** is one of: Done (issue closed), In review (open PR, with the PR it is stacked on), Ready (every blocker closed), or Blocked (with the owners of the open blockers).\n")
	p("- **Acceptance** links the task file, whose Acceptance checklist is the definition of done.\n\n")

	p("## 1. Requirements to issues\n\n")
	p("| Requirement | Synopsis objective | Verified by | Issues |\n|---|---|---|---|\n")
	for _, o := range objectives {
		var refs []string
		for _, item := range strings.Split(o.items, ", ") {
			for _, t := range tasks {
				if hasLabel(t, "item:"+item) && !contains(refs, fmt.Sprintf("#%d", t.Number)) {
					refs = append(refs, fmt.Sprintf("#%d", t.Number))
				}
			}
		}
		p("| %s | %s | %s | %s |\n", o.items, o.objective, o.verified, strings.Join(refs, " "))
	}

	p("\n## 2. Issue-level matrix\n\n")
	p("| Issue | Task | Requirement | Owner | Reviewer | Blocked by | Unblocks | Status | Acceptance |\n")
	p("|---|---|---|---|---|---|---|---|---|\n")
	counts := map[string]int{}
	waitingOn := map[string][]string{}
	for _, t := range tasks {
		id, title := t.Title, ""
		if m := reTaskID.FindStringSubmatch(t.Title); m != nil {
			id, title = m[1], m[2]
		}
		var deps []string
		var openOwners []string
		for _, n := range blockedBy[t.Number] {
			d := byNum[n]
			ref := fmt.Sprintf("#%d", n)
			if d == nil {
				deps = append(deps, ref)
				continue
			}
			owner := owners(d)
			if d.State == "CLOSED" {
				deps = append(deps, ref+" ✓")
			} else {
				deps = append(deps, ref+" ("+owner+")")
				for _, o := range strings.Split(owner, ", ") {
					if !contains(openOwners, o) {
						openOwners = append(openOwners, o)
					}
				}
			}
		}
		var next []string
		for _, n := range unblocks[t.Number] {
			next = append(next, fmt.Sprintf("#%d", n))
		}
		status, kind := statusOf(t, prsFor[t.Number], headPR, openOwners)
		counts[kind]++
		if kind == "Blocked" {
			for _, o := range openOwners {
				waitingOn[o] = append(waitingOn[o], fmt.Sprintf("#%d", t.Number))
			}
		}
		acc := "-"
		if m := reTaskFile.FindStringSubmatch(t.Body); m != nil {
			acc = fmt.Sprintf("[%s](tasks/%s)", strings.TrimSuffix(m[1], ".md"), m[1])
		}
		p("| #%d | %s %s | %s | %s | %s | %s | %s | %s | %s |\n",
			t.Number, id, escape(title), requirement(t), owners(t), reviewer(t),
			orDash(strings.Join(deps, ", ")), orDash(strings.Join(next, " ")), status, acc)
	}

	p("\n## 3. Totals\n\n")
	p("| Status | Issues |\n|---|---|\n")
	for _, k := range []string{"Done", "In review", "Ready", "Blocked"} {
		p("| %s | %d |\n", k, counts[k])
	}

	p("\n## 4. Who is holding whom\n\n")
	p("Open issues that cannot start until this person's open issues merge.\n\n")
	p("| Person | Blocked issues waiting on them |\n|---|---|\n")
	var who []string
	for k := range waitingOn {
		who = append(who, k)
	}
	sort.Strings(who)
	for _, k := range who {
		p("| %s | %s |\n", k, strings.Join(waitingOn[k], " "))
	}

	p("\n## 5. Cross-check: task file against issue links\n\n")
	p("The task file's **Depends on** line is compared with the issue's `Blocked by:` line.\n")
	p("**Gate** is a condition that is not an issue (a checkpoint, a team rule, an installed tool), so the issue links cannot express it.\n")
	p("**Missing link** is a task named in the task file that `Blocked by:` does not reach, directly or through another blocker.\n\n")
	p("| Issue | Depends on (task file) | Gate | Missing link |\n|---|---|---|---|\n")
	for _, t := range tasks {
		m := reDepends.FindStringSubmatch(t.Body)
		if m == nil {
			continue
		}
		text := strings.TrimSpace(m[1])
		ids := expandIDs(text)
		// A dependency reachable through another blocker is covered
		// transitively and is not a missing link.
		have := map[int]bool{}
		stack := append([]int(nil), blockedBy[t.Number]...)
		for len(stack) > 0 {
			n := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			if have[n] {
				continue
			}
			have[n] = true
			stack = append(stack, blockedBy[n]...)
		}
		var missing []string
		for _, id := range ids {
			if n, ok := idToIssue[id]; ok && !have[n] && n != t.Number {
				missing = append(missing, fmt.Sprintf("%s (#%d)", id, n))
			}
		}
		gate := reIDRange.ReplaceAllString(text, "")
		gate = strings.Trim(strings.NewReplacer("`", "", "()", "", ",", " ", ";", " ", "merged", "").Replace(gate), " ")
		gate = strings.Join(strings.Fields(gate), " ")
		if strings.HasPrefix(text, "nothing") || gate == "to start" || gate == "and" {
			gate = ""
		}
		if gate == "" && len(missing) == 0 {
			continue
		}
		p("| #%d | %s | %s | %s |\n", t.Number, escape(text), orDash(escape(gate)), orDash(strings.Join(missing, ", ")))
	}
	os.Stdout.WriteString(w.String())
}

// expandIDs returns every task id in a Depends on line, expanding ranges
// such as "T0.02 to T0.08" within one phase.
func expandIDs(text string) []string {
	var out []string
	for _, m := range reIDRange.FindAllStringSubmatch(text, -1) {
		phase, from := m[1], atoi(m[2])
		to := from
		if m[3] != "" && m[3] == phase {
			to = atoi(m[4])
		}
		for i := from; i <= to; i++ {
			out = append(out, fmt.Sprintf("T%s.%02d", phase, i))
		}
	}
	return out
}

func atoi(s string) int {
	n, _ := strconv.Atoi(s)
	return n
}

func blockers(t *issue) []int {
	m := reBlocked.FindStringSubmatch(t.Body)
	if m == nil {
		return nil
	}
	var out []int
	for _, r := range reRef.FindAllStringSubmatch(m[1], -1) {
		n, _ := strconv.Atoi(r[1])
		out = append(out, n)
	}
	return out
}

func statusOf(t *issue, prs []pull, headPR map[string]int, openOwners []string) (string, string) {
	if t.State == "CLOSED" {
		for _, pr := range prs {
			if pr.State == "MERGED" {
				return fmt.Sprintf("Done (PR #%d)", pr.Number), "Done"
			}
		}
		return "Done", "Done"
	}
	for _, pr := range prs {
		if pr.State != "OPEN" {
			continue
		}
		s := fmt.Sprintf("In review: PR #%d", pr.Number)
		if base, ok := headPR[pr.BaseRefName]; ok && pr.BaseRefName != "main" {
			s += fmt.Sprintf(", stacked on #%d", base)
		}
		return s, "In review"
	}
	if len(openOwners) == 0 {
		return "Ready", "Ready"
	}
	return "Blocked on " + strings.Join(openOwners, ", "), "Blocked"
}

func requirement(t *issue) string {
	var items []string
	for _, l := range t.Labels {
		if strings.HasPrefix(l.Name, "item:") {
			items = append(items, strings.TrimPrefix(l.Name, "item:"))
		}
	}
	sort.Strings(items)
	return orDash(strings.Join(items, ", "))
}

func owners(t *issue) string {
	var names []string
	for _, a := range t.Assignees {
		if n, ok := people[a.Login]; ok {
			names = append(names, n)
		} else {
			names = append(names, a.Login)
		}
	}
	if len(names) == 0 {
		return "unassigned"
	}
	return strings.Join(names, ", ")
}

func reviewer(t *issue) string {
	m := reReviewer.FindStringSubmatch(t.Body)
	if m == nil {
		return "-"
	}
	r := strings.TrimSpace(m[1])
	return strings.ReplaceAll(r, "Ritk", "Ritik")
}

func hasLabel(t *issue, name string) bool {
	for _, l := range t.Labels {
		if l.Name == name {
			return true
		}
	}
	return false
}

func contains(xs []string, x string) bool {
	for _, v := range xs {
		if v == x {
			return true
		}
	}
	return false
}

func escape(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
